module instruction_memory (
    input wire [31:0] address,
    output wire [31:0] instruction
);

    reg [31:0] memory [0:255];

    integer i;

    initial begin

        // Fill memory with NOPs
        for (i = 0; i < 256; i = i + 1)
            memory[i] = 32'h00000013;

        // =========================================
        // FINAL RV32I CPU INTEGRATION TEST
        // =========================================

        // -----------------------------------------
        // 1. ARITHMETIC
        // -----------------------------------------

        // x1 = 10
        memory[0] = 32'h00A00093;

        // x2 = 5
        memory[1] = 32'h00500113;

        // x3 = x1 + x2 = 15
        memory[2] = 32'h002081B3;

        // x4 = x1 - x2 = 5
        memory[3] = 32'h40208233;

        // -----------------------------------------
        // 2. LOGICAL
        // -----------------------------------------

        // x5 = x1 AND x2 = 0
        memory[4] = 32'h0020F2B3;

        // x6 = x1 OR x2 = 15
        memory[5] = 32'h0020E333;

        // x7 = x1 XOR x2 = 15
        memory[6] = 32'h0020C3B3;

        // -----------------------------------------
        // 3. SHIFT
        // -----------------------------------------

        // x8 = x1 << 1 = 20
        memory[7] = 32'h00109433;

        // x9 = x1 >> 1 = 5
        memory[8] = 32'h0010D4B3;

        // -----------------------------------------
        // 4. COMPARISON
        // -----------------------------------------

        // x10 = (5 < 10) = 1
        memory[9] = 32'h0020A533;

        // -----------------------------------------
        // 5. IMMEDIATE ARITHMETIC
        // -----------------------------------------

        // x11 = x1 + 20 = 30
        memory[10] = 32'h01408593;

        // -----------------------------------------
        // 6. STORE / LOAD
        // -----------------------------------------

        // SW x11, 0(x0)
        memory[11] = 32'h00B02023;

        // LW x12, 0(x0)
        memory[12] = 32'h00002603;

        // -----------------------------------------
        // 7. BRANCH
        // -----------------------------------------

        // BEQ x12, x11, +8
        // Skip memory[14]
        memory[13] = 32'h00B60463;

        // Should be skipped
        // x13 = 99
        memory[14] = 32'h06300693;

        // x13 = 13
        memory[15] = 32'h00D00693;

        // -----------------------------------------
        // 8. LUI
        // -----------------------------------------

        // x14 = 0x12345000
        memory[16] = 32'h12345737;

        // -----------------------------------------
        // 9. AUIPC
        // -----------------------------------------

        // PC = 68
        // x15 = 68 + 0x1000 = 0x1044
        memory[17] = 32'h00001797;

        // -----------------------------------------
        // 10. JAL
        // -----------------------------------------

        // JAL x16, +8
        // x16 = PC + 4
        // Skip memory[19]
        memory[18] = 32'h0080086F;

        // Should be skipped
        // x17 = 99
        memory[19] = 32'h06300893;

        // Target
        // x17 = 17
        memory[20] = 32'h01100893;

    end

    assign instruction = memory[address[9:2]];

endmodule